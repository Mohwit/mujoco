"""
Record the REAL MuJoCo run of the closed-loop controller and embed it
in 16-capstone-warehouse-robot.html.

The dashboard used to re-simulate the robot in JavaScript, which drifted
from what MuJoCo actually did. Now it replays recorded physics, so the
page always matches the simulation. Re-run this after changing the
model or the controller:

    uv run --python .venv/bin/python lessons/16-capstone-warehouse-robot/export_trajectory.py
    uv run --python .venv/bin/python lessons/16-capstone-warehouse-robot/export_trajectory.py --policy lessons/16-capstone-warehouse-robot/models/grasp_sac_best/best_model.zip
"""

import importlib
import json
import re
import sys
from pathlib import Path

import mujoco
import numpy as np

from warehouse_common import XML_PATH, body_id, get_chassis_pose, sensor_val, world_to_chassis

HERE = Path(__file__).parent
HTML = HERE / "16-capstone-warehouse-robot.html"
RECORD_HZ = 20
SHELF_EDGES = [(-1.10, 1.5), (1.10, -1.0)]   # front-edge x and centre y of shelf A, B


def shelf_ahead(cx, cy, yaw):
    """Forward distance (m, chassis frame) to the front edge of the shelf the
    robot is facing, or None. Used to draw the shelf in the side view."""
    for edge_x, sy in SHELF_EDGES:
        c = np.cos(yaw)
        if abs(c) < 0.9 or abs(cy - sy) > 0.3:
            continue
        d = (edge_x - cx) / c
        if 0.0 < d < 1.5:
            return d
    return None


def main():
    cl = importlib.import_module("16_capstone_closed_loop")
    model = mujoco.MjModel.from_xml_path(str(XML_PATH))
    data = mujoco.MjData(model)
    mujoco.mj_resetDataKeyframe(model, data, 0)
    mujoco.mj_forward(model, data)
    policy = cl.load_policy()
    ctrl = cl.PickPlaceController(model, data, policy=policy, verbose=False)

    jadr = {n: model.jnt_qposadr[mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, n)]
            for n in ["arm_yaw", "shoulder_pitch", "elbow_pitch", "wrist_pitch"]}
    wheel_dof = [model.jnt_dofadr[mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, n)]
                 for n in ["wheel_FL_spin", "wheel_FR_spin", "wheel_RL_spin", "wheel_RR_spin"]]
    box_id = body_id(model, "red_box")
    cyl_id = body_id(model, "blue_cyl")
    every = int(round(1.0 / (RECORD_HZ * model.opt.timestep)))

    frames, k = [], 0
    while not ctrl.done:
        if k % every == 0:
            x, y, yaw = get_chassis_pose(model, data)
            box = data.xpos[box_id]
            box_c = world_to_chassis(model, data, box)
            acc = sensor_val(model, data, "imu_accel")
            gyr = sensor_val(model, data, "imu_gyro")
            shelf = shelf_ahead(x, y, yaw)
            frames.append([
                round(data.time, 2), ctrl.phase_idx,
                round(x, 3), round(y, 3), round(yaw, 3),
                round(box[0], 3), round(box[1], 3), round(box[2], 3),
                round(box_c[0], 3), round(box_c[2], 3),
                *[round(float(data.qpos[jadr[n]]), 3) for n in jadr],
                round(float(sensor_val(model, data, "sens_gripper")[0]), 4),
                round(float(sensor_val(model, data, "touch_L")[0]), 1),
                round(float(sensor_val(model, data, "touch_R")[0]), 1),
                round(float(sensor_val(model, data, "forward_range")[0]), 2),
                *[round(float(v), 2) for v in acc], *[round(float(v), 2) for v in gyr],
                *[round(float(data.qvel[i]), 1) for i in wheel_dof],
                None if shelf is None else round(shelf, 3),
            ])
        ctrl.step()
        mujoco.mj_step(model, data)
        k += 1

    tgt = data.site_xpos[mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_SITE, "target_site")]
    payload = {
        "fields": ["t", "phase", "x", "y", "yaw", "bx", "by", "bz", "bcx", "bcz",
                   "armYaw", "sh", "el", "wp", "grip", "tL", "tR", "range",
                   "ax", "ay", "az", "gx", "gy", "gz", "wFL", "wFR", "wRL", "wRR", "shelf"],
        "phases": ctrl.phases,
        "results": [[n, s, round(e, 2)] for n, s, e in ctrl.results],
        "mode": "RL policy" if policy else "classical IK",
        "cyl": [round(v, 3) for v in data.xpos[cyl_id][:2]],
        "target": [round(v, 3) for v in tgt[:2]],
        "frames": frames,
    }
    blob = json.dumps(payload, separators=(",", ":"))
    html = HTML.read_text()
    new_block = f"// TRAJECTORY-BEGIN (generated by export_trajectory.py)\nconst TRAJ = {blob};\n// TRAJECTORY-END"
    html, n = re.subn(r"// TRAJECTORY-BEGIN.*?// TRAJECTORY-END", lambda _: new_block, html, flags=re.S)
    if n != 1:
        sys.exit("TRAJECTORY markers not found in HTML")
    HTML.write_text(html)
    print(f"Recorded {len(frames)} frames ({data.time:.1f} s sim) at {RECORD_HZ} Hz "
          f"→ {HTML.name} ({len(html) / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
